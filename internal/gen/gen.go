// Package gen generates types_gen.go and resources_gen.go from contract/orbtr-v1.json.
//
// It reads the contract's components.schemas (objects, enums, arrays, nullable types, string-or-array unions
// and discriminated unions) and its paths' x-orbtr-* operation fields. A schema reachable from a request body
// becomes a params struct whose optional fields are pointers with omitempty; one reachable from a response or
// a stream becomes a struct that keeps its raw JSON. internal/cmd/generate writes the files, and
// generated_test.go regenerates in memory and fails when they differ.
package gen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"regexp"
	"sort"
	"strings"
)

const header = "// Code generated by internal/cmd/generate from contract/orbtr-v1.json. DO NOT EDIT.\n\n"

// Schema is the subset of a JSON Schema object the contract uses.
type Schema struct {
	Ref                  string             `json:"$ref"`
	Type                 json.RawMessage    `json:"type"`
	Description          string             `json:"description"`
	Properties           map[string]*Schema `json:"properties"`
	Required             []string           `json:"required"`
	Items                *Schema            `json:"items"`
	OneOf                []*Schema          `json:"oneOf"`
	Enum                 []string           `json:"enum"`
	AdditionalProperties any                `json:"additionalProperties"`
	Discriminator        *struct {
		PropertyName string            `json:"propertyName"`
		Mapping      map[string]string `json:"mapping"`
	} `json:"discriminator"`
	StreamFlag   bool     `json:"x-orbtr-stream-flag"`
	Source       string   `json:"x-orbtr-source"`
	SourceSubset bool     `json:"x-orbtr-source-subset"`
	SourceAdds   []string `json:"x-orbtr-source-adds"`

	// PropOrder is Properties' keys in contract order.
	PropOrder []string `json:"-"`
}

// UnmarshalJSON keeps the order of the properties.
func (s *Schema) UnmarshalJSON(b []byte) error {
	type alias Schema
	if err := json.Unmarshal(b, (*alias)(s)); err != nil {
		return err
	}
	var raw struct {
		Properties json.RawMessage `json:"properties"`
	}
	if err := json.Unmarshal(b, &raw); err != nil {
		return err
	}
	order, err := orderedKeys(raw.Properties)
	if err != nil {
		return err
	}
	s.PropOrder = order
	return nil
}

// Types names the schema's JSON types.
func (s *Schema) Types() []string {
	if len(s.Type) == 0 {
		return nil
	}
	var one string
	if json.Unmarshal(s.Type, &one) == nil {
		return []string{one}
	}
	var many []string
	_ = json.Unmarshal(s.Type, &many)
	return many
}

func (s *Schema) isRequired(p string) bool {
	for _, r := range s.Required {
		if r == p {
			return true
		}
	}
	return false
}

// Parameter is one path or query parameter.
type Parameter struct {
	Name        string  `json:"name"`
	In          string  `json:"in"`
	Description string  `json:"description"`
	Schema      *Schema `json:"schema"`
}

// Operation is one route of the contract.
type Operation struct {
	Path     string
	Method   string
	Resource string `json:"x-orbtr-resource"`
	Name     string `json:"x-orbtr-method"`
	Summary  string `json:"summary"`
	Scope    string `json:"x-orbtr-scope"`
	Idem     bool   `json:"x-orbtr-idempotency-key"`
	Stream   *struct {
		Event   string `json:"event"`
		Framing string `json:"framing"`
	} `json:"x-orbtr-stream"`
	RequestBody *struct {
		Content map[string]struct {
			Schema *Schema `json:"schema"`
		} `json:"content"`
	} `json:"requestBody"`
	Parameters []Parameter `json:"parameters"`
	Responses  map[string]struct {
		Content map[string]struct {
			Schema *Schema `json:"schema"`
		} `json:"content"`
	} `json:"responses"`
}

// Contract is the parsed contract with its keys in order.
type Contract struct {
	Schemas     map[string]*Schema
	SchemaOrder []string
	Ops         []*Operation
}

func orderedKeys(raw json.RawMessage) ([]string, error) {
	if len(raw) == 0 {
		return nil, nil
	}
	dec := json.NewDecoder(bytes.NewReader(raw))
	if _, err := dec.Token(); err != nil {
		return nil, err
	}
	var keys []string
	for dec.More() {
		t, err := dec.Token()
		if err != nil {
			return nil, err
		}
		keys = append(keys, t.(string))
		var skip json.RawMessage
		if err := dec.Decode(&skip); err != nil {
			return nil, err
		}
	}
	return keys, nil
}

// Parse reads a contract.
func Parse(data []byte) (*Contract, error) {
	var top struct {
		Paths      json.RawMessage `json:"paths"`
		Components struct {
			Schemas json.RawMessage `json:"schemas"`
		} `json:"components"`
	}
	if err := json.Unmarshal(data, &top); err != nil {
		return nil, err
	}
	c := &Contract{}
	if err := json.Unmarshal(top.Components.Schemas, &c.Schemas); err != nil {
		return nil, err
	}
	var err error
	if c.SchemaOrder, err = orderedKeys(top.Components.Schemas); err != nil {
		return nil, err
	}
	paths, err := orderedKeys(top.Paths)
	if err != nil {
		return nil, err
	}
	var items map[string]json.RawMessage
	if err := json.Unmarshal(top.Paths, &items); err != nil {
		return nil, err
	}
	for _, p := range paths {
		methods, err := orderedKeys(items[p])
		if err != nil {
			return nil, err
		}
		var ops map[string]*Operation
		if err := json.Unmarshal(items[p], &ops); err != nil {
			return nil, err
		}
		for _, m := range methods {
			op := ops[m]
			op.Path, op.Method = p, strings.ToUpper(m)
			c.Ops = append(c.Ops, op)
		}
	}
	return c, nil
}

func refName(ref string) string { return ref[strings.LastIndex(ref, "/")+1:] }

func (o *Operation) body() string {
	if o.RequestBody == nil {
		return ""
	}
	return refName(o.RequestBody.Content["application/json"].Schema.Ref)
}

func (o *Operation) response() (name string, ndjson bool) {
	for ctype, c := range o.Responses["200"].Content {
		return refName(c.Schema.Ref), ctype == "application/x-ndjson"
	}
	return "", false
}

var initialisms = map[string]string{"id": "ID", "url": "URL", "json": "JSON", "ot": "OT", "api": "API", "http": "HTTP", "uri": "URI"}

var wordRE = regexp.MustCompile(`[A-Z]?[a-z0-9]+|[A-Z]+`)

// GoName is the exported Go identifier for a JSON field or contract word.
func GoName(s string) string {
	var b strings.Builder
	for _, part := range regexp.MustCompile(`[._\s]+`).Split(s, -1) {
		for _, w := range wordRE.FindAllString(part, -1) {
			if up, ok := initialisms[strings.ToLower(w)]; ok {
				b.WriteString(up)
				continue
			}
			b.WriteString(strings.ToUpper(w[:1]) + w[1:])
		}
	}
	return b.String()
}

func refsIn(s *Schema) []string {
	var out []string
	if s.Ref != "" {
		out = append(out, refName(s.Ref))
	}
	if s.Items != nil {
		out = append(out, refsIn(s.Items)...)
	}
	for _, o := range s.OneOf {
		out = append(out, refsIn(o)...)
	}
	for _, p := range s.Properties {
		out = append(out, refsIn(p)...)
	}
	return out
}

func (c *Contract) closure(start []string) map[string]bool {
	seen := map[string]bool{}
	todo := append([]string(nil), start...)
	for len(todo) > 0 {
		n := todo[len(todo)-1]
		todo = todo[:len(todo)-1]
		if seen[n] {
			continue
		}
		seen[n] = true
		todo = append(todo, refsIn(c.Schemas[n])...)
	}
	return seen
}

// Sides reports which schemas requests use and which responses use.
func (c *Contract) Sides() (req, resp map[string]bool, err error) {
	var rs, ps []string
	for _, o := range c.Ops {
		if b := o.body(); b != "" {
			rs = append(rs, b)
		}
		r, _ := o.response()
		ps = append(ps, r)
		if o.Stream != nil {
			ps = append(ps, refName(o.Stream.Event))
		}
	}
	req, resp = c.closure(rs), c.closure(ps)
	for n := range req {
		if resp[n] {
			return nil, nil, fmt.Errorf("%s is used by both requests and responses", n)
		}
	}
	return req, resp, nil
}

func comment(b *strings.Builder, indent, text string) {
	if text == "" {
		return
	}
	fmt.Fprintf(b, "%s// %s\n", indent, text)
}

func primitive(t string) (string, error) {
	switch t {
	case "string":
		return "string", nil
	case "integer":
		return "int64", nil
	case "number":
		return "float64", nil
	case "boolean":
		return "bool", nil
	}
	return "", fmt.Errorf("unsupported type %q", t)
}

func (c *Contract) elemType(s *Schema) (string, error) {
	if s.Ref != "" {
		return refName(s.Ref), nil
	}
	ts := s.Types()
	if len(ts) != 1 {
		return "", fmt.Errorf("array items must have one type")
	}
	if ts[0] == "object" {
		return "map[string]any", nil
	}
	return primitive(ts[0])
}

// fieldType is a property's Go type and whether its tag carries omitempty.
func (c *Contract) fieldType(s *Schema, required, request bool) (string, bool, error) {
	if s.Ref != "" {
		name := refName(s.Ref)
		if required {
			return name, false, nil
		}
		return "*" + name, true, nil
	}
	if len(s.OneOf) > 0 {
		if len(s.OneOf) != 2 || len(s.OneOf[0].Types()) != 1 || s.OneOf[0].Types()[0] != "string" || s.OneOf[1].Items == nil {
			return "", false, fmt.Errorf("only string-or-array unions are supported in fields")
		}
		elem, err := c.elemType(s.OneOf[1].Items)
		if err != nil {
			return "", false, err
		}
		t := "StringOr[" + elem + "]"
		if required {
			return t, false, nil
		}
		return "*" + t, true, nil
	}
	ts := s.Types()
	nullable := len(ts) == 2 && ts[1] == "null"
	if nullable {
		p, err := primitive(ts[0])
		return "*" + p, false, err
	}
	if len(ts) != 1 {
		return "", false, fmt.Errorf("unsupported type list %v", ts)
	}
	switch ts[0] {
	case "array":
		elem, err := c.elemType(s.Items)
		return "[]" + elem, !required, err
	case "object":
		return "map[string]any", !required, nil
	}
	p, err := primitive(ts[0])
	if err != nil {
		return "", false, err
	}
	if !required && request {
		return "*" + p, true, nil
	}
	return p, !required, nil
}

func describe(c *Contract, s *Schema) string {
	d := s.Description
	if d == "" && s.Ref != "" {
		d = c.Schemas[refName(s.Ref)].Description
	}
	if len(s.Enum) > 1 {
		quoted := make([]string, len(s.Enum))
		for i, e := range s.Enum {
			quoted[i] = fmt.Sprintf("%q", e)
		}
		d += " One of " + strings.Join(quoted, ", ") + "."
	}
	return d
}

func (c *Contract) genTypes() ([]byte, error) {
	req, resp, err := c.Sides()
	if err != nil {
		return nil, err
	}
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("package orbtr\n\nimport \"encoding/json\"\n\n")
	for _, name := range c.SchemaOrder {
		s := c.Schemas[name]
		if !req[name] && !resp[name] {
			return nil, fmt.Errorf("%s is used by no operation", name)
		}
		if len(s.OneOf) > 0 {
			if s.Discriminator == nil || req[name] {
				return nil, fmt.Errorf("%s: only discriminated response unions are supported at the top level", name)
			}
			if err := c.genUnion(&b, name, s); err != nil {
				return nil, err
			}
			continue
		}
		comment(&b, "", name+" is "+lowerFirst(s.Description))
		fmt.Fprintf(&b, "type %s struct {\n", name)
		for _, p := range s.PropOrder {
			ps := s.Properties[p]
			if request := req[name]; request && ps.StreamFlag {
				continue
			}
			t, omit, err := c.fieldType(ps, s.isRequired(p), req[name])
			if err != nil {
				return nil, fmt.Errorf("%s.%s: %w", name, p, err)
			}
			comment(&b, "\t", describe(c, ps))
			tag := p
			if omit {
				tag += ",omitempty"
			}
			fmt.Fprintf(&b, "\t%s %s `json:%q`\n", GoName(p), t, tag)
		}
		if resp[name] {
			b.WriteString("\n\traw json.RawMessage\n")
		}
		b.WriteString("}\n\n")
		if resp[name] {
			fmt.Fprintf(&b, "// UnmarshalJSON reads a %s and keeps its JSON for RawJSON.\n", name)
			fmt.Fprintf(&b, "func (r *%s) UnmarshalJSON(data []byte) error {\n\ttype plain %s\n", name, name)
			b.WriteString("\tif err := json.Unmarshal(data, (*plain)(r)); err != nil {\n\t\treturn err\n\t}\n")
			b.WriteString("\tr.raw = append(json.RawMessage(nil), data...)\n\treturn nil\n}\n\n")
			fmt.Fprintf(&b, "// RawJSON is the JSON the %s was read from, with any field this version does not know.\n", name)
			fmt.Fprintf(&b, "func (r %s) RawJSON() string { return string(r.raw) }\n\n", name)
		}
	}
	return format.Source([]byte(b.String()))
}

func lowerFirst(s string) string {
	if s == "" {
		return s
	}
	if strings.HasPrefix(s, "A ") || strings.HasPrefix(s, "An ") || strings.HasPrefix(s, "The ") || strings.HasPrefix(s, "One ") ||
		strings.HasPrefix(s, "How ") || strings.HasPrefix(s, "What ") || strings.HasPrefix(s, "Where ") || strings.HasPrefix(s, "Tokens ") {
		return strings.ToLower(s[:1]) + s[1:]
	}
	return s
}

func (c *Contract) genUnion(b *strings.Builder, name string, s *Schema) error {
	byRef := map[string]string{}
	for value, ref := range s.Discriminator.Mapping {
		byRef[refName(ref)] = value
	}
	comment(b, "", name+" is "+lowerFirst(s.Description)+" Type names the event, and the field for that type is set.")
	fmt.Fprintf(b, "type %s struct {\n\t// Type is the event's type.\n\tType string `json:%q`\n", name, s.Discriminator.PropertyName)
	type variant struct{ field, ref, value string }
	var vs []variant
	for _, o := range s.OneOf {
		ref := refName(o.Ref)
		value, ok := byRef[ref]
		if !ok {
			return fmt.Errorf("%s: %s has no discriminator value", name, ref)
		}
		field := strings.TrimSuffix(ref, "Event")
		vs = append(vs, variant{field, ref, value})
		fmt.Fprintf(b, "\t// %s is set when Type is %q.\n\t%s *%s `json:\"-\"`\n", field, value, field, ref)
	}
	b.WriteString("\n\traw json.RawMessage\n}\n\n")
	fmt.Fprintf(b, "// UnmarshalJSON reads the event's type and then the event, and keeps its JSON for RawJSON.\n")
	fmt.Fprintf(b, "func (e *%s) UnmarshalJSON(data []byte) error {\n", name)
	fmt.Fprintf(b, "\tvar head struct {\n\t\tType string `json:%q`\n\t}\n", s.Discriminator.PropertyName)
	b.WriteString("\tif err := json.Unmarshal(data, &head); err != nil {\n\t\treturn err\n\t}\n")
	fmt.Fprintf(b, "\t*e = %s{Type: head.Type, raw: append(json.RawMessage(nil), data...)}\n", name)
	b.WriteString("\tswitch head.Type {\n")
	for _, v := range vs {
		fmt.Fprintf(b, "\tcase %q:\n\t\te.%s = new(%s)\n\t\treturn json.Unmarshal(data, e.%s)\n", v.value, v.field, v.ref, v.field)
	}
	b.WriteString("\t}\n\treturn nil\n}\n\n")
	fmt.Fprintf(b, "// MarshalJSON writes the JSON the event was read from.\n")
	fmt.Fprintf(b, "func (e %s) MarshalJSON() ([]byte, error) {\n\tif e.raw != nil {\n\t\treturn e.raw, nil\n\t}\n", name)
	fmt.Fprintf(b, "\treturn json.Marshal(struct {\n\t\tType string `json:%q`\n\t}{e.Type})\n}\n\n", s.Discriminator.PropertyName)
	fmt.Fprintf(b, "// RawJSON is the event's JSON data.\nfunc (e %s) RawJSON() string { return string(e.raw) }\n\n", name)
	return nil
}

type node struct {
	key      string
	segs     []string
	ops      []*Operation
	children []string
}

func (c *Contract) tree() ([]*node, map[string]*node) {
	byKey := map[string]*node{}
	var order []*node
	for _, op := range c.Ops {
		segs := strings.Split(op.Resource, ".")
		for i := 1; i <= len(segs); i++ {
			key := strings.Join(segs[:i], ".")
			if byKey[key] == nil {
				n := &node{key: key, segs: segs[:i]}
				byKey[key] = n
				order = append(order, n)
			}
			if i > 1 {
				parent := byKey[strings.Join(segs[:i-1], ".")]
				found := false
				for _, ch := range parent.children {
					found = found || ch == key
				}
				if !found {
					parent.children = append(parent.children, key)
				}
			}
		}
		byKey[op.Resource].ops = append(byKey[op.Resource].ops, op)
	}
	return order, byKey
}

var methodNames = map[string]string{"create": "Create", "countTokens": "CountTokens", "list": "List", "retrieve": "Get", "cancel": "Cancel", "results": "Results"}

func (c *Contract) streamFlag(body string) string {
	s := c.Schemas[body]
	for _, p := range s.PropOrder {
		if s.Properties[p].StreamFlag {
			return p
		}
	}
	return ""
}

func (c *Contract) genResources() ([]byte, error) {
	order, byKey := c.tree()
	var b strings.Builder
	for _, n := range order {
		svc := GoName(n.key) + "Service"
		var paths []string
		seen := map[string]bool{}
		for _, o := range n.ops {
			if !seen[o.Path] {
				seen[o.Path] = true
				paths = append(paths, o.Path)
			}
		}
		if len(paths) > 0 {
			fmt.Fprintf(&b, "// %s calls the %s routes.\n", svc, strings.Join(paths, ", "))
		} else {
			fmt.Fprintf(&b, "// %s groups the %s resources.\n", svc, n.key)
		}
		fmt.Fprintf(&b, "type %s struct {\n\tclient *Client\n", svc)
		for _, ch := range n.children {
			cn := byKey[ch]
			fmt.Fprintf(&b, "\t// %s calls the %s resources.\n\t%s *%sService\n", GoName(cn.segs[len(cn.segs)-1]), ch, GoName(cn.segs[len(cn.segs)-1]), GoName(ch))
		}
		b.WriteString("}\n\n")
		fmt.Fprintf(&b, "func new%s(c *Client) *%s {\n\treturn &%s{client: c", svc, svc, svc)
		for _, ch := range n.children {
			cn := byKey[ch]
			fmt.Fprintf(&b, ", %s: new%sService(c)", GoName(cn.segs[len(cn.segs)-1]), GoName(ch))
		}
		b.WriteString("}\n}\n\n")
		for _, op := range n.ops {
			if err := c.genMethod(&b, svc, op); err != nil {
				return nil, err
			}
		}
	}
	b.WriteString("// resources are the API's resources, one per top-level path segment; Client embeds them.\ntype resources struct {\n")
	var roots []*node
	for _, n := range order {
		if len(n.segs) == 1 {
			roots = append(roots, n)
		}
	}
	for _, r := range roots {
		fmt.Fprintf(&b, "\t// %s calls the %s resources.\n\t%s *%sService\n", GoName(r.key), r.key, GoName(r.key), GoName(r.key))
	}
	b.WriteString("}\n\nfunc newResources(c *Client) resources {\n\treturn resources{\n")
	for _, r := range roots {
		fmt.Fprintf(&b, "\t\t%s: new%sService(c),\n", GoName(r.key), GoName(r.key))
	}
	b.WriteString("\t}\n}\n")
	body := b.String()
	imports := []string{"context"}
	if strings.Contains(body, "url.") {
		imports = append(imports, "net/url")
	}
	if strings.Contains(body, "strconv.") {
		imports = append(imports, "strconv")
	}
	var out strings.Builder
	out.WriteString(header)
	out.WriteString("package orbtr\n\nimport (\n")
	for _, imp := range imports {
		fmt.Fprintf(&out, "\t%q\n", imp)
	}
	out.WriteString(")\n\n")
	out.WriteString(body)
	return format.Source([]byte(out.String()))
}

func (c *Contract) genMethod(b *strings.Builder, svc string, op *Operation) error {
	name := methodNames[op.Name]
	if name == "" {
		return fmt.Errorf("no Go name for method %q", op.Name)
	}
	resp, ndjson := op.response()
	args := []string{"ctx context.Context"}
	var pathParams, queryParams []Parameter
	for _, p := range op.Parameters {
		if p.In == "path" {
			pathParams = append(pathParams, p)
			args = append(args, p.Name+" string")
		} else {
			queryParams = append(queryParams, p)
		}
	}
	body := op.body()
	if body != "" {
		args = append(args, "params "+body)
	}
	if len(queryParams) > 0 {
		qt := GoName(op.Resource) + GoName(op.Name) + "Params"
		fmt.Fprintf(b, "// %s are the query parameters of %s %s.\ntype %s struct {\n", qt, op.Method, op.Path, qt)
		for _, q := range queryParams {
			t, _, err := c.fieldType(q.Schema, false, true)
			if err != nil {
				return err
			}
			fmt.Fprintf(b, "\t// %s\n\t%s %s\n", q.Description, GoName(q.Name), t)
		}
		b.WriteString("}\n\n")
		fmt.Fprintf(b, "func (p %s) values() url.Values {\n\tv := url.Values{}\n", qt)
		for _, q := range queryParams {
			field := GoName(q.Name)
			switch q.Schema.Types()[0] {
			case "integer":
				fmt.Fprintf(b, "\tif p.%s != nil {\n\t\tv.Set(%q, strconv.FormatInt(*p.%s, 10))\n\t}\n", field, q.Name, field)
			case "boolean":
				fmt.Fprintf(b, "\tif p.%s != nil {\n\t\tv.Set(%q, strconv.FormatBool(*p.%s))\n\t}\n", field, q.Name, field)
			default:
				fmt.Fprintf(b, "\tif p.%s != nil {\n\t\tv.Set(%q, *p.%s)\n\t}\n", field, q.Name, field)
			}
		}
		b.WriteString("\treturn v\n}\n\n")
		args = append(args, "params "+qt)
	}
	args = append(args, "opts ...RequestOption")
	pathExpr := fmt.Sprintf("%q", op.Path)
	if len(pathParams) > 0 {
		pathExpr = fmt.Sprintf("%q", op.Path)
		for _, p := range pathParams {
			pathExpr = strings.Replace(pathExpr, "{"+p.Name+"}", `" + url.PathEscape(`+p.Name+`) + "`, 1)
		}
		pathExpr = strings.TrimSuffix(pathExpr, ` + ""`)
	}
	reqFields := []string{fmt.Sprintf("method: %q", op.Method), "path: " + pathExpr}
	if len(queryParams) > 0 {
		reqFields = append(reqFields, "query: params.values()")
	}
	if op.Idem {
		reqFields = append(reqFields, "idempotent: true")
	}
	summary := strings.ToLower(op.Summary[:1]) + strings.TrimSuffix(op.Summary[1:], ".")
	plainFields := reqFields
	if body != "" {
		plainFields = append(append([]string(nil), reqFields...), "body: params")
	}
	fmt.Fprintf(b, "// %s calls %s %s to %s. It needs the %s scope.\n", name, op.Method, op.Path, summary, op.Scope)
	if ndjson {
		fmt.Fprintf(b, "func (s *%s) %s(%s) ([]%s, error) {\n", svc, name, strings.Join(args, ", "), resp)
		fmt.Fprintf(b, "\tvar out []%s\n\terr := s.client.doNDJSON(ctx, request{%s}, func(line []byte) error {\n", resp, strings.Join(plainFields, ", "))
		fmt.Fprintf(b, "\t\tvar v %s\n\t\tif err := unmarshal(line, &v); err != nil {\n\t\t\treturn err\n\t\t}\n\t\tout = append(out, v)\n\t\treturn nil\n\t}, opts)\n", resp)
		b.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n\treturn out, nil\n}\n\n")
		return nil
	}
	fmt.Fprintf(b, "func (s *%s) %s(%s) (*%s, error) {\n", svc, name, strings.Join(args, ", "), resp)
	fmt.Fprintf(b, "\tvar out %s\n\tif err := s.client.doJSON(ctx, request{%s}, &out, opts); err != nil {\n\t\treturn nil, err\n\t}\n\treturn &out, nil\n}\n\n", resp, strings.Join(plainFields, ", "))
	if op.Stream == nil {
		return nil
	}
	flag := c.streamFlag(body)
	streamFields := append(append([]string(nil), reqFields...), fmt.Sprintf("body: struct {\n\t\t%s\n\t\tStream bool `json:%q`\n\t}{params, true}", body, flag))
	fmt.Fprintf(b, "// %sStreaming calls %s %s with %s: true to %s, the reply arriving as server-sent events. It needs the %s scope.\n",
		name, op.Method, op.Path, flag, summary, op.Scope)
	if op.Stream.Framing == "anthropic" {
		fmt.Fprintf(b, "func (s *%s) %sStreaming(%s) (*MessageStream, error) {\n", svc, name, strings.Join(args, ", "))
		fmt.Fprintf(b, "\treturn s.client.messageStream(ctx, request{%s}, opts)\n}\n\n", strings.Join(streamFields, ", "))
		return nil
	}
	event := refName(op.Stream.Event)
	fmt.Fprintf(b, "func (s *%s) %sStreaming(%s) (*Stream[%s], error) {\n", svc, name, strings.Join(args, ", "), event)
	fmt.Fprintf(b, "\treturn chunkStream[%s](ctx, s.client, request{%s}, opts)\n}\n\n", event, strings.Join(streamFields, ", "))
	return nil
}

// Generate returns the generated files by name.
func Generate(data []byte) (map[string][]byte, error) {
	c, err := Parse(data)
	if err != nil {
		return nil, err
	}
	types, err := c.genTypes()
	if err != nil {
		return nil, fmt.Errorf("types_gen.go: %w", err)
	}
	res, err := c.genResources()
	if err != nil {
		return nil, fmt.Errorf("resources_gen.go: %w", err)
	}
	return map[string][]byte{"types_gen.go": types, "resources_gen.go": res}, nil
}

// SortedNames returns the generated files' names in order.
func SortedNames(files map[string][]byte) []string {
	names := make([]string, 0, len(files))
	for n := range files {
		names = append(names, n)
	}
	sort.Strings(names)
	return names
}
